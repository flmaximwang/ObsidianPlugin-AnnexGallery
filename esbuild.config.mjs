import esbuild from "esbuild";
import fs from "fs";
import path from "path";
import { builtinModules } from "node:module";

const banner = `/*
Annex Gallery — bundle built from main.ts / scripts/cli.ts by esbuild.config.mjs.
Do not edit this file by hand; run \`npm run build\`.
*/`;

const production = process.argv[2] === "production";

// The canonical default .gitattributes / .gitignore live as plain files under
// src/defaults/ (they are diffed against the live repo by the plan's checks),
// so inline them as text at build time instead of keeping a second copy in TS.
const defaultsTextLoader = {
  name: "defaults-text",
  setup(build) {
    build.onLoad({ filter: /\/defaults\/(gitattributes|gitignore|metadata\/[^/]+\.md|base\/[^/]+\.base)$/ }, async (args) => ({
      contents: await fs.promises.readFile(args.path, "utf8"),
      loader: "text",
    }));
  },
};

const nodeBuiltins = [...builtinModules, ...builtinModules.map((m) => `node:${m}`)];

const pluginOptions = {
  banner: { js: banner },
  entryPoints: ["main.ts"],
  bundle: true,
  external: ["obsidian", "electron", ...nodeBuiltins],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  plugins: [defaultsTextLoader],
};

const cliOptions = {
  // No shebang here: scripts/cli.ts carries its own first-line shebang, and
  // esbuild hoists it to line 1 — emitting one here too produced a *double*
  // shebang and `node tools/annex-gallery.mjs` died with SyntaxError on line 2.
  //
  // `yaml` (brought in by src/core/gallery.ts) is CJS and calls `require("process")`;
  // in an ESM bundle esbuild's `__require` shim throws "Dynamic require … is not
  // supported" unless a real `require` exists in scope. createRequire gives it one.
  banner: {
    js: `${banner}
import { createRequire as __annexCreateRequire } from "node:module";
const require = __annexCreateRequire(import.meta.url);`,
  },
  entryPoints: ["scripts/cli.ts"],
  bundle: true,
  external: [...nodeBuiltins],
  platform: "node",
  format: "esm",
  target: "node18",
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outfile: "tools/annex-gallery.mjs",
  plugins: [defaultsTextLoader],
};

if (production) {
  await esbuild.build(pluginOptions);
  await esbuild.build(cliOptions);
  await fs.promises.chmod(path.resolve("tools/annex-gallery.mjs"), 0o755);
} else {
  const pluginCtx = await esbuild.context(pluginOptions);
  const cliCtx = await esbuild.context(cliOptions);
  await pluginCtx.watch();
  await cliCtx.watch();
  console.log("[annex-gallery] watching main.ts and scripts/cli.ts …");
}
